-- Esquema inicial para Grove Market (ShopArmas GTA) adaptado a PostgreSQL / Neon.

-- 1. Roles disponibles para las cuentas de la tienda.
CREATE TABLE IF NOT EXISTS Rol (
    id_rol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- 2. Cuentas de usuario, saldo ficticio y puntos RP.
CREATE TABLE IF NOT EXISTS Usuario (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INT NOT NULL,
    nombre_usuario VARCHAR(80) NOT NULL,
    correo VARCHAR(254) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    saldo DECIMAL(12,2) NOT NULL DEFAULT 100000.00,
    puntos_rp INT NOT NULL DEFAULT 0,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES Rol(id_rol),
    CONSTRAINT chk_usuario_saldo CHECK (saldo >= 0),
    CONSTRAINT chk_usuario_rp CHECK (puntos_rp >= 0)
);

-- 3. Estados de conservacion de las armas/productos.
CREATE TABLE IF NOT EXISTS EstadoArma (
    id_estado_arma INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_estado VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- 4. Categorias que se usan como filtros en el catalogo de la pagina.
CREATE TABLE IF NOT EXISTS Categoria (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- 5. Subcategorias dentro de cada categoria del catalogo.
CREATE TABLE IF NOT EXISTS Subcategoria (
    id_subcategoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_subcategoria VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    id_categoria INT NOT NULL,
    CONSTRAINT fk_subcategoria_categoria FOREIGN KEY (id_categoria) REFERENCES Categoria(id_categoria),
    CONSTRAINT uq_subcategoria_categoria UNIQUE (nombre_subcategoria, id_categoria)
);

-- 6. Inventario: descripcion, precio, unidades, categoria y estadisticas GTA.
CREATE TABLE IF NOT EXISTS Producto (
    id_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto VARCHAR(150) NOT NULL,
    slug VARCHAR(160) NOT NULL UNIQUE,
    descripcion TEXT,
    precio DECIMAL(12,2) NOT NULL,
    puntos_rp INT NOT NULL DEFAULT 0,
    stock INT NOT NULL DEFAULT 0,
    id_estado_arma INT NOT NULL,
    id_subcategoria INT NOT NULL,
    dano SMALLINT NOT NULL DEFAULT 0,
    precision_arma SMALLINT NOT NULL DEFAULT 0,
    alcance SMALLINT NOT NULL DEFAULT 0,
    es_drop BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_producto_estado FOREIGN KEY (id_estado_arma) REFERENCES EstadoArma(id_estado_arma),
    CONSTRAINT fk_producto_subcategoria FOREIGN KEY (id_subcategoria) REFERENCES Subcategoria(id_subcategoria),
    CONSTRAINT chk_producto_precio CHECK (precio >= 0),
    CONSTRAINT chk_producto_stock CHECK (stock >= 0),
    CONSTRAINT chk_producto_rp CHECK (puntos_rp >= 0),
    CONSTRAINT chk_producto_dano CHECK (dano >= 0 AND dano <= 100),
    CONSTRAINT chk_producto_precision CHECK (precision_arma >= 0 AND precision_arma <= 100),
    CONSTRAINT chk_producto_alcance CHECK (alcance >= 0 AND alcance <= 100)
);

-- 7. Imagenes asociadas a cada ficha de producto.
CREATE TABLE IF NOT EXISTS ImagenProducto (
    id_imagen INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INT NOT NULL,
    url_imagen VARCHAR(500) NOT NULL,
    imagen_principal BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_imagen_producto FOREIGN KEY (id_producto) REFERENCES Producto(id_producto) ON DELETE CASCADE
);

-- 8. Armas que cada usuario marco como favoritas.
CREATE TABLE IF NOT EXISTS Favorito (
    id_usuario INT NOT NULL,
    id_producto INT NOT NULL,
    fecha_agregado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_usuario, id_producto),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_favorito_producto FOREIGN KEY (id_producto) REFERENCES Producto(id_producto) ON DELETE CASCADE
);

-- 9. Regiones y comunas para las direcciones de despacho.
CREATE TABLE IF NOT EXISTS Region (
    id_region INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_region VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS Comuna (
    id_comuna INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_comuna VARCHAR(100) NOT NULL,
    id_region INT NOT NULL,
    CONSTRAINT fk_comuna_region FOREIGN KEY (id_region) REFERENCES Region(id_region),
    CONSTRAINT uq_comuna_region UNIQUE (nombre_comuna, id_region)
);

-- 10. Direcciones de los usuarios para las compras con despacho.
CREATE TABLE IF NOT EXISTS Direccion (
    id_direccion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_comuna INT NOT NULL,
    calle VARCHAR(150) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    departamento VARCHAR(50),
    codigo_postal VARCHAR(15),
    referencia VARCHAR(255),
    CONSTRAINT fk_direccion_usuario FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario),
    CONSTRAINT fk_direccion_comuna FOREIGN KEY (id_comuna) REFERENCES Comuna(id_comuna)
);

-- 11. Estados posibles del ciclo de vida de una venta.
CREATE TABLE IF NOT EXISTS EstadoVenta (
    id_estado_venta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_estado VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- 12. Opciones de entrega y sus costos.
CREATE TABLE IF NOT EXISTS MetodoEnvio (
    id_metodo_envio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_metodo VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    costo DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_envio_costo CHECK (costo >= 0)
);

-- 13. Cabecera de compra: comprador, direccion, envio, estado y montos.
CREATE TABLE IF NOT EXISTS Venta (
    id_venta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_direccion INT NULL,
    id_estado_venta INT NOT NULL,
    id_metodo_envio INT NOT NULL,
    fecha_venta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    subtotal DECIMAL(12,2) NOT NULL,
    costo_envio DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_venta_usuario FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario),
    CONSTRAINT fk_venta_direccion FOREIGN KEY (id_direccion) REFERENCES Direccion(id_direccion) ON DELETE SET NULL,
    CONSTRAINT fk_venta_estado FOREIGN KEY (id_estado_venta) REFERENCES EstadoVenta(id_estado_venta),
    CONSTRAINT fk_venta_envio FOREIGN KEY (id_metodo_envio) REFERENCES MetodoEnvio(id_metodo_envio),
    CONSTRAINT chk_venta_subtotal CHECK (subtotal >= 0),
    CONSTRAINT chk_venta_costo_envio CHECK (costo_envio >= 0),
    CONSTRAINT chk_venta_total CHECK (total >= 0)
);

-- 14. Lineas de productos comprados y precio historico al momento de la venta.
CREATE TABLE IF NOT EXISTS DetalleVenta (
    id_detalle_venta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta INT NOT NULL,
    id_producto INT NOT NULL,
    cantidad INT NOT NULL,
    precio_unitario DECIMAL(12,2) NOT NULL,
    subtotal DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta) REFERENCES Venta(id_venta),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES Producto(id_producto),
    CONSTRAINT chk_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_detalle_precio CHECK (precio_unitario >= 0),
    CONSTRAINT chk_detalle_subtotal CHECK (subtotal >= 0)
);

-- 15. Saldo ficticio disponible para el carrito/monedero de demostracion.
CREATE TABLE IF NOT EXISTS Cartera (
    id_usuario INT PRIMARY KEY,
    saldo DECIMAL(12,2) NOT NULL DEFAULT 100000.00,
    actualizada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cartera_usuario FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT chk_cartera_saldo CHECK (saldo >= 0)
);

-- Reemplaza ON UPDATE CURRENT_TIMESTAMP de MySQL para Cartera.actualizada_en.
CREATE OR REPLACE FUNCTION actualizar_fecha_cartera()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizada_en := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_cartera_actualizada_en ON Cartera;
CREATE TRIGGER trg_cartera_actualizada_en
BEFORE UPDATE ON Cartera
FOR EACH ROW
EXECUTE FUNCTION actualizar_fecha_cartera();
